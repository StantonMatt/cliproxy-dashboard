const assert = require('node:assert/strict');
const {describe} = require('../dashboard/static/billing.js');
const now = new Date(2026, 8, 23, 23, 59);
const billing = {renewal_date:'2026-10-14', confirmed:true};
const normal = describe(billing, now);
assert.equal(normal.date, '14 Oct 2026');
assert.equal(normal.badge, 'In 21 days');
assert.equal(normal.note, 'Review by 12 Oct · two days before renewal');
assert.equal(normal.urgent, false);
assert.equal(describe(billing, new Date(2026, 9, 13)).badge, 'Tomorrow');
assert.equal(describe(billing, new Date(2026, 9, 14)).badge, 'Today');
assert.equal(describe(billing, new Date(2026, 9, 15)).badge, 'Check date');
const ended = describe(billing, new Date(2026, 9, 15), 'free');
assert.equal(ended.label, 'Plan ended');
assert.equal(ended.date, '14 Oct 2026');
assert.equal(ended.urgent, false);
assert.equal(ended.ended, true);
assert.equal(describe({...billing, confirmed:false}, new Date(2026, 9, 15), 'free').label, 'Plan ended');
assert.equal(describe(billing, new Date(2026, 9, 14), 'free').ended, undefined);
assert.equal(describe(billing, new Date(2026, 9, 13), 'free').urgent, true);
assert.equal(describe(billing, new Date(2026, 9, 15), 'pro').ended, undefined);
assert.equal(describe(billing, new Date(2026, 9, 15), null).ended, undefined);
assert.equal(describe({renewal_date:'invalid'}, now, 'free').date, 'Not available');
assert.equal(describe({...billing, confirmed:false}, now).label, 'Expected renewal');
assert.match(describe({...billing, confirmed:false}, now).note, /Unconfirmed/);
// A date rolled forward from one the user set says so, until it passes in turn.
const inferred = {...billing, confirmed:false, source:'renewal_inferred'};
assert.equal(describe(inferred, now).label, 'Expected renewal');
assert.equal(describe(inferred, now).note, 'Estimate · a month after the date you set.');
assert.match(describe(inferred, new Date(2026, 9, 15)).note, /Date passed/);
assert.equal(describe({renewal_date:'2026-02-30'}, now).date, 'Not available');
assert.equal(describe(undefined, now).date, 'Not available');
assert.match(describe({renewal_date:'2027-01-01', confirmed:true}, now).note, /30 Dec/);
// Local calendar days, rather than 24-hour durations, survive DST changes.
assert.equal(describe({renewal_date:'2026-03-09', confirmed:true}, new Date(2026, 2, 7, 23)).badge, 'In 2 days');
console.log('Billing dates: calendar, time-zone, DST, rollover, missing-data, and confirmation checks passed.');
